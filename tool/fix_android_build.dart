String? _flutterVersion() {
  try {
    final result = Process.runSync(
      'flutter',
      ['--version', '--machine'],
      runInShell: true,
    );
    if (result.exitCode != 0) return null;
    final decoded = jsonDecode(result.stdout.toString());
    if (decoded is! Map) return null;
    final framework = decoded['frameworkVersion'];
    return framework is String ? framework : null;
  } catch (_) {
    return null;
  }
}

/// Runs a command and keeps its output to itself, for probes whose chatter
/// would bury the lines the user needs to read.
int _runQuiet(String executable, List<String> args) {
  try {
    return Process.runSync(executable, args, runInShell: true).exitCode;
  } catch (_) {
    return 1;
  }
}

/// Runs a command, streaming nothing but its exit code. `runInShell` is needed
/// on Windows, where `flutter` and `dart` are `.bat` shims.
int _run(String executable, List<String> args, {String? workingDirectory}) {
  final result = Process.runSync(
    executable,
    args,
    workingDirectory: workingDirectory,
    runInShell: true,
  );
  final out = result.stdout.toString().trim();
  if (out.isNotEmpty) stdout.writeln(out);
  final err = result.stderr.toString().trim();
  if (err.isNotEmpty) stderr.writeln(err);
  return result.exitCode;
}

Directory _projectRoot() {
  var dir = Directory.current;
  while (!File('${dir.path}/pubspec.yaml').existsSync()) {
    final parent = dir.parent;
    if (parent.path == dir.path) return Directory.current;
    dir = parent;
  }
  return dir;
}

String _short(Directory root, File file) =>
    file.path.replaceFirst('${root.path}${Platform.pathSeparator}', '');

Never _fail(String message) {
  stderr.writeln(message);
  exit(1);
}
