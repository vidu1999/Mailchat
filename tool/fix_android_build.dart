/// Sets `compileSdk` to [sdk] in a Groovy or Kotlin module-level build file.
///
/// Handles every shape the Flutter templates have used:
///
/// ```text
/// compileSdkVersion 34          (old Groovy template)
/// compileSdkVersion = 34
/// compileSdk 34
/// compileSdk = 34
/// compileSdkVersion flutter.compileSdkVersion   (left alone: the SDK decides)
/// compileSdk = flutter.compileSdkVersion
/// ```
///
/// A symbolic value is deliberately untouched: when it resolves to something
/// older than we need, the Flutter SDK itself is too old, and hiding that behind
/// a literal number would move the failure somewhere less obvious.
String pinCompileSdk(
  String gradle, {
  int sdk = requiredCompileSdk,
  bool kotlinDsl = false,
}) {
  var out = gradle;

  // Symbolic values: leave them to the Flutter Gradle plugin.
  final symbolic = RegExp(
    r'compileSdk(?:Version)?\s*=?\s*(flutter|rootProject|project)\.[A-Za-z.]+',
  );
  if (symbolic.hasMatch(out)) return out;

  final withNumber = RegExp(r'compileSdk(?:Version)?(\s*=?\s*)(\d+)');
  if (withNumber.hasMatch(out)) {
    return out.replaceAllMapped(withNumber, (match) {
      final current = int.parse(match.group(2)!);
      // Only ever raise. A project that already compiles against something
      // newer must not be dragged back to 36 by a tool that exists to fix an
      // older value.
      if (current >= sdk) return match.group(0)!;
      final separator = match.group(1) ?? ' ';
      // Keep the file's own style. Kotlin DSL has no `compileSdkVersion`
      // property at all, so a `.kts` file always gets the assignment form.
      final isAssignment = kotlinDsl || separator.contains('=');
      return isAssignment ? 'compileSdk = $sdk' : 'compileSdkVersion $sdk';
    });
  }

  // No compileSdk line at all: insert one at the top of the `android { ... }`
  // block, which is where both templates put it.
  final block = RegExp(r'(android\s*\{)');
  if (block.hasMatch(out)) {
    return out.replaceFirstMapped(
      block,
      (match) => '${match.group(1)}\n    compileSdk = $sdk',
    );
  }
  return out;
}

/// True when [version] is at least [minimum], comparing dotted numbers.
///
/// Anything unparseable counts as too old: refusing to guess is the safe
/// direction, because the alternative is a Java error 40 lines long.
bool versionAtLeast(String version, String minimum) {
  final a = _numericParts(version);
  final b = _numericParts(minimum);
  if (a == null || b == null) return false;
  for (var i = 0; i < b.length; i++) {
    final left = i < a.length ? a[i] : 0;
    if (left != b[i]) return left > b[i];
  }
  return true;
}

List<int>? _numericParts(String value) {
  final match = RegExp(r'^(\d+(?:\.\d+)*)').firstMatch(value.trim());
  if (match == null) return null;
  return match.group(1)!.split('.').map(int.parse).toList();
}

