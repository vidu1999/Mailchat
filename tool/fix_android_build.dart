// Repairs the generated Android project so the call stack (flutter_webrtc) can
// actually compile.
//
//   dart run tool/fix_android_build.dart              # diagnose + patch in place
//   dart run tool/fix_android_build.dart --reset --yes  # regenerate android/ first
//
// Why this exists: `flutter_webrtc` 1.6.3 needs two things from the Flutter SDK
// that older versions do not provide, and both failures are reported as a wall
// of Java rather than as "your Flutter is too old":
//
//   1. Flutter >= 3.29 ships `TextureRegistry.SurfaceProducer.Callback` with
//      `onSurfaceCleanup()`. Older engines only declare `onSurfaceDestroyed()`
//      as an abstract method, and the plugin writes `onSurfaceCleanup` — so
//      `:flutter_webrtc:compileDebugJavaWithJavac` fails with
//      "is not abstract and does not override abstract method
//      onSurfaceDestroyed()".
//   2. Flutter < 3.35 defaults `compileSdk` to 34 or 35; the plugin compiles
//      against 36. The fix is either a newer SDK (3.35 sets 36 by default) or
//      an explicit `compileSdk = 36` in android/app/build.gradle — which is
//      what this script writes, because an `android/` folder generated by an
//      older SDK keeps its old number even after `flutter upgrade`.
//
// Also note the plugin's own pubspec says `flutter: ">=1.22.0"`, which is why
// `flutter pub get` never warns about any of this.
//
// Idempotent: running it twice changes nothing.

import 'dart:convert';
import 'dart:io';

/// The lowest Flutter SDK that provides both the `onSurfaceCleanup` callback and
/// a default compileSdk of 36.
const String requiredFlutterVersion = '3.35.0';

/// What `flutter_webrtc` 1.6.3 compiles against (its android/build.gradle).
const int requiredCompileSdk = 36;

void main(List<String> args) {
  final checkOnly = args.contains('--check');
  final reset = args.contains('--reset');
  final confirmed = args.contains('--yes') || args.contains('-y');
  final root = _projectRoot();
  var problems = 0;

  // ---- 1. Flutter SDK ----------------------------------------------------
  final version = _flutterVersion();
  if (version == null) {
    _fail('Could not run `flutter --version --machine`. Is Flutter on PATH?');
  }
  stdout.writeln('Flutter $version (need >= $requiredFlutterVersion for call media)');
  if (!versionAtLeast(version, requiredFlutterVersion)) {
    stderr.writeln('');
    stderr.writeln('✗ Your Flutter is too old for flutter_webrtc.');
    stderr.writeln('  Before $requiredFlutterVersion the Android embedding declares an abstract');
    stderr.writeln('  onSurfaceDestroyed() that the plugin does not implement, so the Java');
    stderr.writeln('  compile fails and no amount of Gradle editing will fix it.');
    stderr.writeln('');
    stderr.writeln('  Run:  flutter upgrade');
    stderr.writeln('  Then: dart run tool/fix_android_build.dart --reset --yes');
    exit(2);
  }
  if (checkOnly) {
    // CI and pre-flight use: the SDK is the only thing that can make the build
    // fail in a way a patch cannot fix.
    stdout.writeln('Flutter SDK is new enough for call media.');
    return;
  }

  // ---- 2. android/ exists? ------------------------------------------------
  final androidDir = Directory('${root.path}/android');
  if (!androidDir.existsSync()) {
    stdout.writeln('android/ is missing — scaffolding it...');
    final result = _run('flutter', [
      'create',
      '--platforms=android',
      '--org',
      'com.mailchat',
      '--project-name',
      'mailchat',
      '.',
    ]);
    if (result != 0) exit(result);
  } else if (reset) {
    if (!confirmed) {
      stderr.writeln('');
      stderr.writeln('--reset would delete ${androidDir.path} and scaffold it again.');
      stderr.writeln('It is not committed, so only local edits are lost — but if you have');
      stderr.writeln('already configured release signing there, back it up first.');
      stderr.writeln('Re-run with --yes to proceed.');
      exit(3);
    }
    stdout.writeln('Deleting android/ and scaffolding it again...');
    androidDir.deleteSync(recursive: true);
    final result = _run('flutter', [
      'create',
      '--platforms=android',
      '--org',
      'com.mailchat',
      '--project-name',
      'mailchat',
      '.',
    ]);
    if (result != 0) exit(result);
  }

  // ---- 3. compileSdk -----------------------------------------------------
  final gradleFiles = [
    File('${androidDir.path}/app/build.gradle'),
    File('${androidDir.path}/app/build.gradle.kts'),
  ].where((f) => f.existsSync()).toList();
  if (gradleFiles.isEmpty) {
    _fail('Neither android/app/build.gradle nor .kts exists.');
  }
  for (final file in gradleFiles) {
    final before = file.readAsStringSync();
    final after = pinCompileSdk(
      before,
      sdk: requiredCompileSdk,
      kotlinDsl: file.path.endsWith('.kts'),
    );
    if (after == before) {
      stdout.writeln('• ${_short(root, file)}: compileSdk already >= $requiredCompileSdk '
          '(or inherited from the Flutter SDK)');
    } else {
      file.writeAsStringSync(after);
      stdout.writeln('✓ ${_short(root, file)}: compileSdk pinned to $requiredCompileSdk');
    }
  }

  // ---- 4. the two platform patchers --------------------------------------
  for (final tool in [
    'tool/enable_deep_links.dart',
    'tool/enable_call_permissions.dart',
  ]) {
    stdout.writeln('');
    final code = _run('dart', ['run', tool], workingDirectory: root.path);
    if (code != 0) {
      stderr.writeln('✗ $tool failed with exit $code');
      problems++;
    }
  }

  stdout.writeln('');
  if (problems > 0) {
    stderr.writeln('$problems problem(s) remain. See docs/running.md § "Build fails in');
    stderr.writeln('flutter_webrtc" for the full explanation.');
    exit(1);
  }
  stdout.writeln('Android build ready. Next:');
  stdout.writeln('  flutter clean && flutter run');
}

